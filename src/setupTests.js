import '@testing-library/jest-dom';

// jsdom has no matchMedia; report "no match" (no reduced motion, fine pointer) like a desktop.
if (!window.matchMedia) {
  window.matchMedia = (query) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  });
}
